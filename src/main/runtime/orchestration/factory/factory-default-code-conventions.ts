  '',
  '---',
  '',
  '## 7. File structure: screen → sections → components',
  '',
  '- A **screen** is the entry point. It composes sections.',
  '- A **section** is a meaningful block of the screen.',
  '- A **component** is a reusable piece inside a section.',
  '',
